import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {chromium} from 'playwright';
const server=spawn('python3',['-m','http.server','8765','--bind','127.0.0.1'],{stdio:'ignore'});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error'&&!/commons\.wikimedia|ERR_FAILED|ERR_ABORTED/.test(m.text()))errors.push(m.text())});
try{
 await page.route('https://commons.wikimedia.org/**',route=>route.abort());
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
 await page.locator('#newsPublisherLinks a').first().waitFor();
 const bg=await page.locator('body').evaluate(x=>getComputedStyle(x).backgroundColor);
 assert.notEqual(bg,'rgb(255, 255, 255)','Dashboard should not render plain white');
 await page.locator('#searchQuery').fill('California flooding');
 await page.locator('#searchButton').click();
 await page.locator('.media-card').first().waitFor();
 const count=await page.locator('.media-card').count();
 assert.ok(count>=3,'Stock video fallback should work even if Commons fails');
 assert.ok(await page.locator('.media-type').first().innerText().then(x=>x.includes('Video')));
 await page.locator('#newsSearch').click();
 await page.locator('#newsSearch').waitFor({state:'visible'});
 await page.waitForFunction(()=>!document.querySelector('#newsSearch').disabled,{timeout:10000});
 const news=await page.locator('#newsResults .r-card').count();
 assert.ok(news>0,'Same-origin cached news must display related articles');
 assert.ok(await page.locator('#socialResearchLinks a').count()>=7);
 await page.locator('[data-tab="scenes"]').click();
 await page.locator('#scriptInput').fill('California faces heavy rain. The Sierra Nevada receives snow.');
 await page.locator('#makeScenes').click();
 assert.equal(await page.locator('.scene-card').count(),2,'Script should split into two scenes');
 await page.locator('[data-tab="discover"]').click();
 await page.locator('.media-card button[data-action="details"]').first().click();
 assert.equal(await page.locator('#detailDialog').evaluate(e=>e.open),true);
 await page.locator('#detailDialog button[data-action="save"]').click();
 await page.locator('#detailDialog form button').click();
 await page.locator('[data-tab="collection"]').click();
 assert.ok(await page.locator('#collectionResults .media-card').count()>=1);
 assert.equal(errors.length,0,'No uncaught browser errors: '+errors.join('; '));
 console.log(JSON.stringify({status:'PASS',bg,videoCards:count,newsCards:news,scenes:2,saved:1,errors}));
}finally{await browser.close();server.kill();}
